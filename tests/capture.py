"""Access to the sanitised real-session fixture.

``tests/fixtures/sb3000tl20_session.json`` (generated by
``scripts/sanitize_capture.py``) holds every frame of one SBFspot Bluetooth session
against an SB 3000TL-20, with its direction and wire bytes.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import smabt.frame as frame_mod
from smabt.const import CMD_L2_FRAGMENT, CMD_L2_LAST

FIXTURE_PATH = Path(__file__).resolve().parent / "fixtures" / "sb3000tl20_session.json"

TX = "tx"
RX = "rx"
FRAGMENT_PAYLOAD = 91
"""Wire bytes of L2 data per fragment as sent by the inverter (L1 length 109)."""


@dataclass(frozen=True)
class CapturedFrame:
    index: int
    direction: str
    wire: bytes
    origin: str

    @property
    def l1(self) -> frame_mod.L1Frame:
        return frame_mod.L1Frame.decode(self.wire)


@dataclass(frozen=True)
class Message:
    """One logical message: a single frame, or the fragments of one L2 packet."""

    direction: str
    frames: tuple[CapturedFrame, ...]

    @property
    def stream(self) -> bytes:
        """Concatenated L1 payloads (the escaped L2 stream for L2 messages)."""
        return b"".join(f.l1.payload for f in self.frames)

    @property
    def l2(self) -> frame_mod.L2Packet:
        return frame_mod.L2Packet.decode(self.stream)

    @property
    def is_l2(self) -> bool:
        return frame_mod.is_l2_start(self.frames[0].l1.payload)


class Capture:
    """Parsed fixture."""

    def __init__(self, data: dict[str, Any]) -> None:
        self.meta: dict[str, Any] = data["meta"]
        self.identifiers: dict[str, Any] = data["identifiers"]
        self.frames = [
            CapturedFrame(i, f["dir"], bytes.fromhex(f["hex"]), f["origin"])
            for i, f in enumerate(data["frames"])
        ]

    @classmethod
    def load(cls) -> Capture:
        return cls(json.loads(FIXTURE_PATH.read_text(encoding="utf-8")))

    @property
    def messages(self) -> list[Message]:
        """Frames grouped into messages (cmd 8 fragments + final cmd 1)."""
        messages: list[Message] = []
        pending: list[CapturedFrame] = []
        for frame in self.frames:
            pending.append(frame)
            if frame.l1.cmd == CMD_L2_FRAGMENT:
                continue
            messages.append(Message(frame.direction, tuple(pending)))
            pending = []
        assert not pending, "fixture ends inside a multi-part packet"
        return messages

    @property
    def inverter_address(self) -> bytes:
        return frame_mod.address_to_bytes(self.identifiers["inverter_bt_address"])

    @property
    def local_address(self) -> bytes:
        return frame_mod.address_to_bytes(self.identifiers["local_bt_address"])

    def exchanges(self) -> list[tuple[Message, list[Message]]]:
        """Each client message with the inverter messages that answer it.

        The inverter's unsolicited announcement (the first message) is not part of
        any exchange; see :attr:`announce`.
        """
        result: list[tuple[Message, list[Message]]] = []
        for message in self.messages[1:]:
            if message.direction == TX:
                result.append((message, []))
            else:
                result[-1][1].append(message)
        return result

    @property
    def announce(self) -> Message:
        first = self.messages[0]
        assert first.direction == RX
        return first


def fragment_stream(
    stream: bytes, src: bytes, dst: bytes, *, size: int = FRAGMENT_PAYLOAD
) -> list[bytes]:
    """Split an escaped L2 stream into L1 frames like the inverter does."""
    chunks = [stream[i : i + size] for i in range(0, len(stream), size)] or [b""]
    frames = []
    for n, chunk in enumerate(chunks):
        cmd = CMD_L2_LAST if n == len(chunks) - 1 else CMD_L2_FRAGMENT
        frames.append(frame_mod.L1Frame(src, dst, cmd, chunk).encode())
    return frames
